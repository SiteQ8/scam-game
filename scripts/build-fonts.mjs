// Copies only the Arabic and Latin font files the app uses and writes their @font-face rules.
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'app/src/assets/fonts');
mkdirSync(out, { recursive: true });
// Start clean so faces the app no longer uses do not linger in the bundle.
for (const f of readdirSync(out)) rmSync(join(out, f));
const KEEP = ['arabic', 'latin', 'latin-ext'];
let css = '/* Generated by scripts/build-fonts.mjs. Aref Ruqaa and Readex Pro, SIL Open Font License 1.1. */\n';
function take(pkgCss, family) {
  const src = readFileSync(join(root, 'node_modules', pkgCss), 'utf8');
  for (const block of src.split('@font-face').slice(1)) {
    const file = (block.match(/url\(\.\/files\/([^)]+\.woff2)\)/) || [])[1];
    const subset = file ? (file.match(/-(arabic|latin-ext|latin|vietnamese|cyrillic-ext|cyrillic|greek-ext|greek)-(?:wght|\d{3})-normal\.woff2$/) || [])[1] : undefined;
    const range = (block.match(/unicode-range:\s*([^;]+);/) || [])[1];
    const weight = (block.match(/font-weight:\s*([^;]+);/) || [])[1];
    if (!file || !KEEP.includes(subset)) continue;
    copyFileSync(join(root, 'node_modules', dirname(pkgCss), 'files', file), join(out, file));
    css += `@font-face{font-family:'${family}';font-style:normal;font-display:swap;font-weight:${weight};src:url(../assets/fonts/${file}) format('woff2');unicode-range:${range};}\n`;
  }
}
take('@fontsource/aref-ruqaa/700.css', 'Aref Ruqaa');
take('@fontsource-variable/readex-pro/wght.css', 'Readex Pro');
// The licence travels with the fonts: beside the files in the source, and inside the app and its web build.
const licences = join(root, 'app/public/licenses');
mkdirSync(licences, { recursive: true });
for (const f of readdirSync(licences)) if (f.startsWith('OFL-')) rmSync(join(licences, f));
for (const [pkg, name] of [['@fontsource/aref-ruqaa', 'OFL-aref-ruqaa.txt'], ['@fontsource-variable/readex-pro', 'OFL-readex-pro.txt']]) {
  copyFileSync(join(root, 'node_modules', pkg, 'LICENSE'), join(out, name));
  copyFileSync(join(root, 'node_modules', pkg, 'LICENSE'), join(licences, name));
}
writeFileSync(join(root, 'app/src/styles/fonts.css'), css);
console.log('fonts written');
